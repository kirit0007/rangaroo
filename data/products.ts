// Helper functions
export function getProductBySlug(slug: string): Product | undefined {
  return products.find(p => p.slug === slug);
}

export function getProductsByCategory(categoryId: string): Product[] {
  return products.filter(p => p.categoryId === categoryId && p.isActive);
}

export function getProductsByCollection(collectionId: string): Product[] {
  return products.filter(p => p.collectionId === collectionId && p.isActive);
}

export function getFeaturedProducts(): Product[] {
  return products.filter(p => p.isFeatured && p.isActive);
}

export function getCategoryBySlug(slug: string): Category | undefined {
  return categories.find(c => c.slug === slug);
}

export function getCollectionBySlug(slug: string): Collection | undefined {
  const cleanSlug = slug.toLowerCase();
  return collections.find(
    c => c.slug === cleanSlug || 
         c.id === cleanSlug || 
         c.slug === `${cleanSlug}-collection` || 
         c.id === cleanSlug.replace('-collection', '')
  );
}

export function formatPrice(price: number): string {
  return `₹${price.toLocaleString('en-IN')}`;
}

export function calculateDiscount(price: number, compareAtPrice: number): number {
  if (!compareAtPrice || compareAtPrice <= price) return 0;
  return Math.round(((compareAtPrice - price) / compareAtPrice) * 100);
}
